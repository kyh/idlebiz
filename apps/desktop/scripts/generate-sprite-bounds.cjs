// Measures every PNG the office can place, keyed by its path under public/. One scan
// of what ships, not a column in each generator: design2 is committed art with no
// generator of its own, and a sprite's size is a fact about its file, not its id.
const fs = require("node:fs");
const path = require("node:path");
const { loadRaw, opaqueBounds } = require("./lib/pixels.cjs");

const appRoot = path.resolve(__dirname, "..");
const publicDir = path.join(appRoot, "public");
const generatedPath = path.join(appRoot, "src/renderer/game/sprite-bounds.generated.ts");
const SPRITE_DIRS = [
  "workspace-kit/office-objects/32",
  "workspace-kit/design2",
  "workspace-kit/room-builder/32",
];

// oxfmt's print width: the output must already be formatted or `pnpm format` fails
const PRINT_WIDTH = 100;

const entryBlock = ({ sprite, w, h, bounds: b }) => {
  const key = JSON.stringify(sprite);
  const value = `{ w: ${w}, h: ${h}, bounds: { x: ${b.x}, y: ${b.y}, w: ${b.w}, h: ${b.h} } }`;
  const line = `  [${key}, ${value}],`;
  return line.length <= PRINT_WIDTH ? line : `  [\n    ${key},\n    ${value},\n  ],`;
};

const writeGenerated = (entries) => {
  const contents = `// Generated by apps/desktop/scripts/generate-sprite-bounds.cjs — do not edit.

/** A shipped sprite's canvas size and the box its opaque pixels fill. */
export interface SpriteBounds {
  readonly w: number;
  readonly h: number;
  readonly bounds: {
    readonly x: number;
    readonly y: number;
    readonly w: number;
    readonly h: number;
  };
}

/** Every placeable sprite, keyed by its path relative to public/. */
export const SPRITE_BOUNDS: ReadonlyMap<string, SpriteBounds> = new Map<string, SpriteBounds>([
${entries.map(entryBlock).join("\n")}
]);
`;
  fs.writeFileSync(generatedPath, contents);
};

const main = async () => {
  const entries = [];
  for (const dir of SPRITE_DIRS) {
    const files = fs
      .readdirSync(path.join(publicDir, dir))
      .filter((file) => file.endsWith(".png"))
      .toSorted();
    for (const file of files) {
      const sprite = `${dir}/${file}`;
      const image = await loadRaw(path.join(publicDir, sprite));
      entries.push({ bounds: opaqueBounds(image), h: image.h, sprite, w: image.w });
    }
  }
  writeGenerated(entries);
  console.log(`measured ${entries.length} sprites`);
};

void main();
